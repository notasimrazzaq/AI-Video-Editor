// Sound effects from one list: projects/<name>/sfx.json = [[time, "sound-name", volume?], ...]
//   node tools/sfx.mjs projects/<name>                         -> writes <audio> tags into index.html (between sfx markers)
//   node tools/sfx.mjs projects/<name> --mix in.mp4 out.mp4    -> also mixes them onto an existing render (video copied, no re-render)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { spawnSync } from "node:child_process";

const DEFAULT_VOL = {
  "paper-flip": 0.32, "paper-drop": 0.28, "paper-rustle": 0.22, "tape-rip": 0.16, "marker-tick": 0.3,
  "marker-scribble": 0.22, stamp: 0.38, "paper-slide": 0.2, thump: 0.45,
  counter: 0.18, pop: 0.22, chime: 0.3, tick: 0.2, snap: 0.25, star: 0.25, switch: 0.25, fill: 0.2, success: 0.3,
  "crisp-click": 0.32, "crisp-pop": 0.32, "crisp-tick": 0.3, "glass-tap": 0.3, "type-burst": 0.25, "count-roll": 0.28,
  whoosh: 0.28, hit: 0.45, ding: 0.28, alert: 0.3, "switch-on": 0.32, send: 0.3, sparkle: 0.32,
};

const [dir, flag, inFile, outFile] = process.argv.slice(2);
if (!dir) throw new Error("Usage: node tools/sfx.mjs projects/<name> [--mix in.mp4 out.mp4]");

const strip = (s) => s.replace(/^\uFEFF/, "");
const events = JSON.parse(strip(readFileSync(join(dir, "sfx.json"), "utf8")))
  .map(([t, name, vol]) => ({ t: Math.max(0, +t), name, vol: vol ?? DEFAULT_VOL[name] ?? 0.25 }))
  .sort((a, b) => a.t - b.t);
for (const e of events) if (!existsSync(join(dir, "sfx", `${e.name}.wav`))) throw new Error(`Missing sfx/${e.name}.wav`);

function wavSeconds(file) {
  const b = readFileSync(file);
  const byteRate = b.readUInt32LE(28);
  for (let p = 12; p + 8 <= b.length; p += 8 + b.readUInt32LE(p + 4)) {
    if (b.toString("ascii", p, p + 4) === "data") return b.readUInt32LE(p + 4) / byteRate;
  }
  throw new Error(`No data chunk in ${file}`);
}
const lengths = {};
for (const e of events) lengths[e.name] ??= Math.ceil(wavSeconds(join(dir, "sfx", `${e.name}.wav`)) * 100) / 100;

// lowest track (from 5) that is free at this time, so no two clips overlap on one track
const trackEnds = [];
for (const e of events) {
  e.dur = lengths[e.name];
  let k = trackEnds.findIndex((end) => end <= e.t);
  if (k === -1) k = trackEnds.push(0) - 1;
  trackEnds[k] = e.t + e.dur + 0.01;
  e.track = 5 + k;
}

// 1) <audio> tags in index.html
const htmlPath = join(dir, "index.html");
let html = readFileSync(htmlPath, "utf8");
const tags = events
  .map((e, i) => `      <audio id="sfx-${String(i + 1).padStart(3, "0")}" src="sfx/${e.name}.wav" data-start="${e.t.toFixed(2)}" data-duration="${e.dur}" data-track-index="${e.track}" data-volume="${e.vol}"></audio>`)
  .join("\n");
const block = `<!-- sfx:start (generated by tools/sfx.mjs from sfx.json) -->\n${tags}\n      <!-- sfx:end -->`;
if (/<!-- sfx:start[\s\S]*?<!-- sfx:end -->/.test(html)) html = html.replace(/<!-- sfx:start[\s\S]*?<!-- sfx:end -->/, block);
else html = html.replace(/(<div id="caps"><\/div>)/, `$1\n      ${block}`);
if (!html.includes("sfx:start")) throw new Error('Could not place sfx block: add <!-- sfx:start --><!-- sfx:end --> inside the root composition.');
writeFileSync(htmlPath, html);
console.log(`index.html: ${events.length} sound effects`);

// 2) optional fast mix onto an existing render
if (flag === "--mix") {
  if (!inFile || !outFile) throw new Error("--mix needs in.mp4 and out.mp4");
  const names = [...new Set(events.map((e) => e.name))];
  const args = ["-v", "error", "-stats", "-y", "-i", inFile];
  names.forEach((n) => args.push("-i", join(dir, "sfx", `${n}.wav`)));
  const parts = [];
  const labels = [];
  names.forEach((n, k) => {
    const uses = events.map((e, i) => ({ e, i })).filter(({ e }) => e.name === n);
    const outs = uses.map(({ i }) => `[s${i}]`).join("");
    parts.push(`[${k + 1}:a]aformat=sample_rates=48000:channel_layouts=stereo,asplit=${uses.length}${outs}`);
    uses.forEach(({ e, i }) => {
      parts.push(`[s${i}]volume=${e.vol},adelay=${Math.round(e.t * 1000)}:all=1[e${i}]`);
      labels[i] = `[e${i}]`;
    });
  });
  parts.push(`[0:a]${labels.join("")}amix=inputs=${events.length + 1}:normalize=0:duration=first,alimiter=limit=0.97[aout]`);
  args.push("-filter_complex", parts.join(";"), "-map", "0:v", "-map", "[aout]", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-movflags", "+faststart", outFile);
  const r = spawnSync("ffmpeg", args, { stdio: "inherit" });
  if (r.status !== 0) throw new Error("ffmpeg mix failed");
  console.log(`Mixed ${events.length} sound effects -> ${outFile}`);
}
